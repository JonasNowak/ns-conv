#!/usr/bin/env python3
"""
ns-conv: scripts/build-pages-bundle.py
Converts ASCII STLs in cad/stl/*.stl into compact binary STLs in docs/models/*.stl,
generates docs/assets/models-bundle.js (gzipped + base64 binary STLs for instant
Three.js WebGL loading on both GitHub Pages and local file://), and generates
docs/assets/guides-bundle.js containing all 10 Phase Markdown guides, OpenSCAD
sources, and BOM data.
"""
import base64
import csv
import gzip
import json
import os
import re
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CAD_STL_DIR = ROOT / "cad" / "stl"
DOCS_MODELS_DIR = ROOT / "docs" / "models"
DOCS_ASSETS_DIR = ROOT / "docs" / "assets"

STL_NAMES = [
    "base_bottom",
    "base_top_deck",
    "lid_rear",
    "lid_bezel",
    "battery_retainer",
    "cable_clamp",
    "test_fit_jig",
]


def ascii_stl_to_binary(ascii_path: Path, bin_path: Path) -> bytes:
    """Convert an OpenSCAD ASCII STL file into a compact binary STL."""
    text = ascii_path.read_text(encoding="utf-8", errors="ignore")
    # Match facet normal nx ny nz ... vertex x1 y1 z1 vertex x2 y2 z2 vertex x3 y3 z3
    pattern = re.compile(
        r"facet\s+normal\s+([^\s]+)\s+([^\s]+)\s+([^\s]+)\s+"
        r"outer\s+loop\s+"
        r"vertex\s+([^\s]+)\s+([^\s]+)\s+([^\s]+)\s+"
        r"vertex\s+([^\s]+)\s+([^\s]+)\s+([^\s]+)\s+"
        r"vertex\s+([^\s]+)\s+([^\s]+)\s+([^\s]+)\s+"
        r"endloop\s+endfacet",
        re.IGNORECASE | re.MULTILINE,
    )
    matches = pattern.findall(text)
    header = f"ns-conv binary STL: {ascii_path.name}".encode("ascii").ljust(80, b"\0")
    out = bytearray(header)
    out += struct.pack("<I", len(matches))
    for m in matches:
        floats = [float(x) for x in m]
        out += struct.pack("<12fH", *floats, 0)
    data = bytes(out)
    bin_path.write_bytes(data)
    return data


def main() -> None:
    DOCS_MODELS_DIR.mkdir(parents=True, exist_ok=True)
    DOCS_ASSETS_DIR.mkdir(parents=True, exist_ok=True)

    models_gz_b64 = {}
    for name in STL_NAMES:
        src = CAD_STL_DIR / f"{name}.stl"
        dst = DOCS_MODELS_DIR / f"{name}.stl"
        bin_bytes = ascii_stl_to_binary(src, dst)
        gz_bytes = gzip.compress(bin_bytes, compresslevel=9)
        models_gz_b64[name] = base64.b64encode(gz_bytes).decode("ascii")
        print(
            f"  [STL] {name}.stl: ASCII {src.stat().st_size/1024:.1f} KB "
            f"-> Binary {len(bin_bytes)/1024:.1f} KB -> Gzip {len(gz_bytes)/1024:.1f} KB"
        )

    models_js = (
        "// Auto-generated by scripts/build-pages-bundle.py\n"
        "window.NS_CONV_MODELS_GZ_B64 = "
        + json.dumps(models_gz_b64, indent=2)
        + ";\n"
    )
    (DOCS_ASSETS_DIR / "models-bundle.js").write_text(models_js, encoding="utf-8")

    # Bundle all Markdown guides + OpenSCAD sources + BOM CSV
    guides = {
        "overview": (ROOT / "README.md").read_text(encoding="utf-8"),
        "phase1_research": (ROOT / "docs" / "research.md").read_text(encoding="utf-8"),
        "phase2_bom": (ROOT / "docs" / "bom.md").read_text(encoding="utf-8"),
        "phase3_teardown": (ROOT / "docs" / "teardown.md").read_text(encoding="utf-8"),
        "phase4_wiring": (ROOT / "docs" / "wiring.md").read_text(encoding="utf-8"),
        "phase5_cad": (ROOT / "docs" / "cad-overview.md").read_text(encoding="utf-8"),
        "phase6_print": (ROOT / "docs" / "print-spec.md").read_text(encoding="utf-8"),
        "phase7_assembly": (ROOT / "docs" / "assembly.md").read_text(encoding="utf-8"),
        "phase8_software": (ROOT / "docs" / "software.md").read_text(encoding="utf-8"),
        "phase9_testing": (ROOT / "docs" / "testing.md").read_text(encoding="utf-8"),
        "phase10_risks": (ROOT / "docs" / "risks.md").read_text(encoding="utf-8"),
        "datasheets": (ROOT / "hardware" / "datasheets.md").read_text(encoding="utf-8"),
    }

    scad_sources = {}
    for scad_file in sorted((ROOT / "cad").glob("*.scad")):
        scad_sources[scad_file.name] = scad_file.read_text(encoding="utf-8")

    bom_rows = []
    with (ROOT / "hardware" / "BOM.csv").open("r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            bom_rows.append(row)

    guides_js = (
        "// Auto-generated by scripts/build-pages-bundle.py\n"
        "window.NS_CONV_GUIDES = "
        + json.dumps(guides, indent=2)
        + ";\n"
        "window.NS_CONV_SCAD = "
        + json.dumps(scad_sources, indent=2)
        + ";\n"
        "window.NS_CONV_BOM = "
        + json.dumps(bom_rows, indent=2)
        + ";\n"
    )
    (DOCS_ASSETS_DIR / "guides-bundle.js").write_text(guides_js, encoding="utf-8")
    print(f"  [OK] Wrote {DOCS_ASSETS_DIR / 'models-bundle.js'}")
    print(f"  [OK] Wrote {DOCS_ASSETS_DIR / 'guides-bundle.js'}")


if __name__ == "__main__":
    main()
